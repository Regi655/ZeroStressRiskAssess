#!/usr/bin/env python3
"""Check that Grype reads the SBOM built by the tool (zerostressriskassess/cve.py) correctly.

Two ways of running Grype are compared on the SAME container:
  A. `grype IMAGE`: Grype opens the image and discovers the packages itself (reference);
  B. the tool's method: package list read inside the container with the INVENTORY script,
     CycloneDX SBOM generated by the tool, `grype sbom:FILE --distro ...`.
If B finds the same CVEs as A, the SBOM is correct; any difference shows where it is not.

Usage (from the project directory, with the lab running: ./lab/lab.sh up):
    grype zerostressriskassess-lab-grave:24.04 -o json > grype-lab.json      # A: Grype on the image
    .venv/bin/python3 tools/verifica_sbom.py zerostressriskassess-lab-grave grype-lab.json
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from zerostressriskassess import cve  # noqa: E402


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2
    container, ref = argv[1], argv[2]
    p = subprocess.run(["docker", "exec", container, "bash", "-c", cve.INVENTORY], capture_output=True, text=True)
    inv = cve.parse_inventory(p.stdout)
    if not inv["pkgs"]:
        print("Elenco dei pacchetti vuoto:", p.stderr[-300:])
        return 1
    print(f"Container: {inv['os']} {inv['version']}, {len(inv['pkgs'])} pacchetti, {len(inv['avail'])} aggiornabili")
    data, err = cve.run_grype(inv)
    if data is None:
        print("Grype sullo SBOM non ha prodotto JSON:", err)
        return 1
    mine = {(v["cve"], v["pkg"]) for v in cve.parse_grype(data)}
    theirs = {(v["cve"], v["pkg"]) for v in cve.parse_grype(json.loads(Path(ref).read_text()))}
    print(f"A (grype immagine): {len(theirs)}   B (SBOM del tool): {len(mine)}   in comune: {len(mine & theirs)}")
    for name, s in (("solo A (il tool le PERDE)", theirs - mine), ("solo B (il tool le AGGIUNGE)", mine - theirs)):
        print(f"\n{name}: {len(s)}")
        for cve_id, pkg in sorted(s)[:25]:
            print(f"  {cve_id:<18} {pkg}")
    c = cve.classify(cve.parse_grype(data), inv["avail"], inv["kind"])
    print(f"\nClassificazione del tool: risolvibili ora {len(c['now'])}, in attesa {len(c['waiting'])}, "
          f"senza correzione {len(c['unfixed'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
