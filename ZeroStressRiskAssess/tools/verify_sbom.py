#!/usr/bin/env python3
"""Check that Grype (or Trivy) reads the SBOM built by the tool (zerostressriskassess/cve.py) correctly.

Two ways of running the scanner are compared on the SAME container:
  A. `grype IMAGE` / `trivy image IMAGE`: the scanner opens the image and discovers the packages itself (reference);
  B. the tool's method: package list read inside the container with the INVENTORY script, CycloneDX SBOM
     generated by the tool, `grype sbom:FILE --distro ...` / `trivy sbom FILE`.
If B finds the same CVEs as A, the SBOM is correct; any difference shows where it is not.

Usage (from the project directory, with the lab running: ./lab/lab.sh up):
    grype zerostressriskassess-lab-severe:24.04 -o json > grype-lab.json      # A: Grype on the image
    .venv/bin/python3 tools/verify_sbom.py zerostressriskassess-lab-severe grype-lab.json

    trivy image --scanners vuln --format json -o trivy-lab.json zerostressriskassess-lab-severe:24.04
    .venv/bin/python3 tools/verify_sbom.py zerostressriskassess-lab-severe trivy-lab.json --trivy
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from zerostressriskassess import cve  # noqa: E402


def main(argv):
    use_trivy = "--trivy" in argv
    argv = [a for a in argv if a != "--trivy"]
    if len(argv) != 3:
        print(__doc__)
        return 2
    container, ref = argv[1], argv[2]
    name, parse = ("Trivy", cve.parse_trivy) if use_trivy else ("Grype", cve.parse_grype)
    p = subprocess.run(["docker", "exec", container, "bash", "-c", cve.INVENTORY], capture_output=True, text=True)
    inv = cve.parse_inventory(p.stdout)
    if not inv["pkgs"]:
        print("Empty package list:", p.stderr[-300:])
        return 1
    print(f"Container: {inv['os']} {inv['version']}, {len(inv['pkgs'])} packages, {len(inv['avail'])} upgradable")
    if use_trivy:
        data, _, err = cve.run_trivy(inv)
    else:
        data, err = cve.run_grype(inv)
    if data is None:
        print(f"{name} produced no JSON for the SBOM:", err)
        return 1
    mine = {(v["cve"], v["pkg"]) for v in parse(data)}
    theirs = {(v["cve"], v["pkg"]) for v in parse(json.loads(Path(ref).read_text()))}
    print(f"A ({name} on image): {len(theirs)}   B (tool SBOM): {len(mine)}   in common: {len(mine & theirs)}")
    for name, s in (("only A (the tool MISSES them)", theirs - mine), ("only B (the tool ADDS them)", mine - theirs)):
        print(f"\n{name}: {len(s)}")
        for cve_id, pkg in sorted(s)[:25]:
            print(f"  {cve_id:<18} {pkg}")
    c = cve.classify(parse(data), inv["avail"], inv["kind"])
    print(f"\nTool classification: fixable now {len(c['now'])}, pending {len(c['waiting'])}, "
          f"without a fix {len(c['unfixed'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
